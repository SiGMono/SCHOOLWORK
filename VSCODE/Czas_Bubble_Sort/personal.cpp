#include <iostream>
#include <vector>
#include <chrono>
#include <random>

using namespace std;

//  Bubble sort as function
void bubbleSort(vector<int>& v) {
    int n = v.size();

    //  Starting time for sorting algorithm
    auto start = chrono::high_resolution_clock::now();

    // Outer loop that corresponds to the number of
    // elements to be sorted
    for (int i = 0; i < n - 1; i++) {

        // Last i elements are already
        // in place
        for (int j = 0; j < n - i - 1; j++) {
          
          	// Comparing adjacent elements
            if (v[j] > v[j + 1])
              
              	// Swapping if in the wrong order
                swap(v[j], v[j + 1]);
        }
    }
    //  Ending time for sorting algorithm and displaying it in miliseconds
    auto end = chrono::high_resolution_clock::now();
    auto dur = end - start;
    auto ms = std::chrono::duration_cast<std::chrono::milliseconds>(dur).count();
    cout << "Algorytm sortowania babelkowego zajal: " << ms << " milisekund."<<endl;
}

int main(int argc, char const *argv[])
{
    //  Random number generator
    random_device dev;
    mt19937 rng(dev());
    uniform_int_distribution<int> dist100000(1, 100000);

    //  User chosen amount of numbers to sort
    int numbers;
    cout<<"Podaj ilosc liczb do posortowania"<<endl;
    cin>>numbers;

    //  Vector array for autogenerated numbers with its filling
    vector<int> numbersArray;
    for(int i = 0; i < numbers; i++){
        numbersArray.push_back(dist100000(rng));
    }

    //  Display unsorted data
    cout << "Unsorted: " <<endl;
    for(auto v : numbersArray){
        cout << v << endl;
    }

    //  Call to sort function
    bubbleSort(numbersArray);

    //  Display sorted data
    cout << "Sorted: " <<endl;
    for(auto v : numbersArray){
        cout << v << endl;
    }

    return 0;
}
